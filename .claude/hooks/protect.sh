#!/usr/bin/env bash
# PreToolUse (Edit|Write|MultiEdit|Bash): refuse a few things that are almost
# always a mistake. Exit 2 blocks the tool call and shows stderr to Claude.
# This repo has no database migrations, so there is no rule for them.
set -uo pipefail

input=$(cat)
tool=$(jq -r '.tool_name // empty' <<<"$input" 2>/dev/null) || exit 0
project=${CLAUDE_PROJECT_DIR:-$(pwd)}

deny() {
    echo "Blocked by .claude/hooks/protect.sh: $1" >&2
    echo "Instead: $2" >&2
    exit 2
}

case $tool in
Edit | Write | MultiEdit)
    file=$(jq -r '.tool_input.file_path // empty' <<<"$input")
    name=${file##*/}
    case $name in
    .env | .env.*)
        deny "$name holds local secrets and is never edited by an agent." \
            "tell the user which variable to set and let them edit it."
        ;;
    Cargo.lock)
        deny "Cargo.lock is generated by cargo and must not be edited by hand." \
            "change the pinned version in the crate's Cargo.toml and run 'cargo update -p <crate>' (or 'cargo update --workspace' after a version bump)."
        ;;
    esac
    ;;
Bash)
    cmd=$(jq -r '.tool_input.command // empty' <<<"$input")

    # Git's global options (-C <dir>, -c <k=v>, --no-pager...) may sit between
    # `git` and the subcommand; requiring the subcommand right after them keeps
    # a commit message that merely mentions "push --force" from matching.
    git_re='(^|[;&|[:space:]])git[[:space:]]+((-C|-c)[[:space:]]+[^[:space:]]+[[:space:]]+|-[^[:space:]]+[[:space:]]+)*'

    # rm with a recursive and a force flag (in any spelling: -rf, -fr, -r -f,
    # --recursive --force) aimed at a broad path. Checked per command segment.
    while IFS= read -r segment; do
        read -ra words <<<"$segment"
        [[ ${words[0]:-} == rm || ${words[0]:-} == sudo && ${words[1]:-} == rm ]] || continue
        recursive=false force=false broad=""
        for word in "${words[@]:1}"; do
            case $word in
            rm) ;;
            --recursive) recursive=true ;;
            --force) force=true ;;
            --*) ;;
            -*)
                [[ $word == *[rR]* ]] && recursive=true
                [[ $word == *f* ]] && force=true
                ;;
            *)
                target=${word//[\"\']/}
                case $target in
                / | '/*' | '~' | '~/' | '~/*' | '$HOME' | '${HOME}' | '$HOME/' | '$HOME/*' | . | ./ | './*' | .. | ../ | '../*' | '*' | .git | .git/)
                    broad=$target
                    ;;
                esac
                ;;
            esac
        done
        if $recursive && $force && [[ -n $broad ]]; then
            deny "'rm -rf $broad' deletes far more than a task needs." \
                "delete the specific files or folder you mean (e.g. 'rm -rf dist'), or run 'cargo clean' for build output."
        fi
    done < <(sed -E 's/(&&|\|\||[;|&])/\n/g' <<<"$cmd")

    if grep -Eq "${git_re}push([[:space:]][^;&|]*)?[[:space:]](--force|-[[:alnum:]]*f[[:alnum:]]*)([[:space:]]|\$)" <<<"$cmd"; then
        deny "'git push --force' can destroy commits on the remote." \
            "push normally; if a rebase really needs it, ask the user, who can run 'git push --force-with-lease' on their own branch."
    fi

    if grep -Eq "${git_re}reset[[:space:]]([^;&|]*[[:space:]])?--hard" <<<"$cmd"; then
        branch=$(git -C "$project" symbolic-ref --quiet --short HEAD 2>/dev/null || echo "")
        if [[ $branch == main || $branch == master ]]; then
            deny "'git reset --hard' on the shared branch '$branch'." \
                "switch to a feature branch first, or use 'git revert' / 'git restore <file>' to undo specific changes."
        fi
    fi
    ;;
esac
exit 0
